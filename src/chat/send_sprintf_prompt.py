# -*- coding: utf-8 -*-
"""Одноразовая отправка полного промпта my_sprintf мозгу, сохранение ответа."""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from neira_api import ask

TASK = """Нейра, задача: реализуй на C функцию `int my_sprintf(char *buffer, const char *format, ...)` — полный аналог `sprintf` (C99/C11).

Спецификаторы: `%d %i %u %o %x %X %e %E %f %F %g %G %c %s %p %n %%`.

Флаги: `-` (влево), `+` (всегда знак), пробел (знак-пробел), `#` (альтернативная форма), `0` (дополнение нулями; игнорируется при `-` и при точности для целых).

Ширина: числом или `*` из аргумента; отрицательная `*` = флаг `-`.

Точность: `.<число>` или `.*`; пустая `%.` = 0; для целых — минимум цифр (точность 0 при значении 0 = пустая строка); для строк — максимум символов; для `f`/`e` — число знаков после точки; для `g` — число значащих цифр (0 трактуется как 1).

Модификаторы длины: `hh h l ll j z t L` — определяют тип аргумента (signed/unsigned char, short, long, long long, intmax_t, size_t, ptrdiff_t, long double).

Семантика: `d/i/u/o/x/X` — целые (буквы строчные для x, прописные для X; префиксы `0`/`0x` только при `#` и ненулевом значении); `e/E` — одна цифра перед точкой, экспонента со знаком и минимум двумя цифрами; `f/F` — без экспоненты; `g/G` — кратчайшая из e и f, удаление хвостовых нулей без явной точности; `c` — символ; `s` — строка до нуля или до точности; `p` — указатель; `n` — запись числа выведенных символов в аргумент-указатель; `%%`.

Вещественные: преобразование по точному двоичному значению с корректным округлением — на середине к чётной цифре, иначе в большую сторону. `inf`/`-inf`/`nan`, знак по значению и флагам, `-0.0` сохраняет минус. Краевые случаи: перенос при округлении (увеличение целой части), очень большие/малые числа, субнормальные, точности до сотен знаков, пустые строки, ширина меньше длины.

Требования:
1. ЗАПРЕЩЕНО использовать `printf`/`snprintf`/`vsnprintf` для генерации результата.
2. Генерация всех цифр — ТОЛЬКО целочисленной арифметикой (BigInt/массивы цифр), без `pow` и без плавающей арифметики в вычислениях цифр.
3. Код устойчив: без переполнений буфера, утечек, падений.
4. Возвращаемое значение — число записанных символов без NUL; буфер завершается NUL.

Верни ТОЛЬКО код функции `my_sprintf` и её `static`-вспомогательные функции. БЕЗ `main`, без тестов, без пояснений, без дублирования задания."""

if __name__ == "__main__":
    out = ask(TASK, temperature=0.2, max_tokens=12000)
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "saved", "sprintf_prompt_answer.txt")
    with open(path, "w", encoding="utf-8") as f:
        f.write(out)
    print("len =", len(out))
    print("saved ->", path)
    print("---- первые 1200 символов ----")
    print(out[:1200])
